// Complete Code 128B encoder
export function generateCode128Svg(text: string, height = 45): string {
  const cleanText = text.trim() || '000000000000';
  const codes: number[] = [104]; // Start Code B

  for (let i = 0; i < cleanText.length; i++) {
    const charCode = cleanText.charCodeAt(i);
    const code = charCode - 32;
    if (code >= 0 && code <= 95) {
      codes.push(code);
    }
  }

  // Calculate Checksum
  let checksum = codes[0];
  for (let i = 1; i < codes.length; i++) {
    checksum += codes[i] * i;
  }
  codes.push(checksum % 103);
  codes.push(106); // Stop Code

  // Build Bar Pattern string
  const patterns = [
    '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312', '132212', '221213',
    '221312', '231212', '112232', '122132', '122231', '113222', '123122', '123221', '223211', '221132',
    '221231', '213212', '223112', '312131', '311222', '321122', '321221', '312212', '322112', '322211',
    '212123', '212321', '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
    '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121', '313121', '211331',
    '231131', '213113', '213311', '213131', '311123', '311321', '331121', '312113', '312311', '332111',
    '314111', '221411', '431111', '111224', '111422', '121124', '121421', '141122', '141221', '112214',
    '112412', '122114', '122411', '142112', '142411', '191112', '191211', '411122', '411221', '421112',
    '421211', '212141', '214121', '412121', '111143', '111341', '131141', '114113', '114311', '411113',
    '411311', '113141', '114131', '311141', '411131', '211412', '211214', '211232', '2331112', '211133',
    '213311', '213131', '214111', '211142', '211241', '211421', '214112', '2331112'
  ];

  let patternStr = '';
  for (const c of codes) {
    patternStr += patterns[c] || patterns[0];
  }

  // Calculate total width in modules
  let totalModules = 0;
  for (let i = 0; i < patternStr.length; i++) {
    totalModules += parseInt(patternStr[i], 10);
  }

  const moduleWidth = 1.5;
  const svgWidth = Math.ceil(totalModules * moduleWidth);

  let svgRects = '';
  let currentX = 0;
  let isBar = true;

  for (let i = 0; i < patternStr.length; i++) {
    const width = parseInt(patternStr[i], 10) * moduleWidth;
    if (isBar) {
      svgRects += `<rect x="${currentX.toFixed(1)}" y="0" width="${width.toFixed(1)}" height="${height}" fill="#000000" />`;
    }
    currentX += width;
    isBar = !isBar;
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${svgWidth} ${height}" width="100%" height="${height}px">${svgRects}</svg>`;
}
